# CELL 3: 🚀 Compress All Videos (Parallel)
# ============================================================
import subprocess, os
from concurrent.futures import ThreadPoolExecutor, as_completed
from tqdm import tqdm

SUPPORTED = ('.mp4', '.mov', '.avi', '.mkv', '.webm', '.m4v', '.flv')

def compress_one(args):
    idx, vpath = args
    serial_name = f'{SERIAL_PREFIX}_{idx:02d}.{OUTPUT_EXT}'
    out_path    = os.path.join(OUTPUT_DIR, serial_name)

    # Build FFmpeg command
    # Corrected: Escaped the backslash for the ffmpeg 'scale' filter
    vf  = f'scale=min({MAX_WIDTH}\\,iw):-2' if MAX_WIDTH else 'scale=trunc(iw/2)*2:trunc(ih/2)*2'
    cmd = ['ffmpeg', '-y', '-i', vpath, '-vf', vf,
           '-c:v', CODEC, '-crf', str(CRF), '-preset', PRESET]
    if CODEC == 'libx265':
        cmd += ['-tag:v', 'hvc1']
    cmd += ['-c:a', 'aac', '-b:a', '64k'] if KEEP_AUDIO else ['-an']
    cmd += ['-movflags', '+faststart', out_path]

    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        return {'ok': False, 'input': os.path.basename(vpath), 'error': r.stderr[:200]}

    orig_kb = os.path.getsize(vpath)    / 1024
    comp_kb = os.path.getsize(out_path) / 1024
    return {
        'ok':            True,
        'idx':           idx,
        'input':         os.path.basename(vpath),
        'output':        out_path,
        'output_name':   serial_name,
        'original_kb':   round(orig_kb, 1),
        'compressed_kb': round(comp_kb, 1),
        'savings_pct':   round((1 - comp_kb / orig_kb) * 100, 1)
    }

# Collect + sort videos
video_files = sorted(
    [f for f in glob.glob(os.path.join(INPUT_DIR, '*'))
     if os.path.splitext(f)[1].lower() in SUPPORTED]
)

if not video_files:
    print('❌ No videos found.')
else:
    total   = len(video_files)
    # Use up to 4 parallel workers (Colab has 2 CPU cores, but IO overlap helps)
    workers = min(4, total)
    print(f'🚀 Compressing {total} video(s) with {workers} parallel workers...\n')

    results_map = {}
    tasks = list(enumerate(video_files, start=1))

    with ThreadPoolExecutor(max_workers=workers) as executor:
        futures = {executor.submit(compress_one, t): t for t in tasks}
        for fut in tqdm(as_completed(futures), total=total, desc='Compressing'):
            res = fut.result()
            if res['ok']:
                results_map[res['idx']] = res
            else:
                print(f'❌ {res["input"]}: {res["error"]}')

    # Sort results by index for ordered display
    results = [results_map[i] for i in sorted(results_map.keys())]

    print(f'\n{"New Name":<35} {"Original":>8} {"Compressed":>11} {"Saved":>7}')
    print('─' * 66)
    for r in results:
        print(f'{r["output_name"][:33]:<35} {r["original_kb"]:>6.1f}KB '
              f'{r["compressed_kb"]:>9.1f}KB {r["savings_pct"]:>6.1f}%')
    print('─' * 66)
    t_orig = sum(r['original_kb']   for r in results)
    t_comp = sum(r['compressed_kb'] for r in results)
    t_save = (1 - t_comp / t_orig) * 100
    print(f'{"TOTAL":<35} {t_orig:>6.1f}KB {t_comp:>9.1f}KB {t_save:>6.1f}%')
    print(f'\n✅ Done! {len(results)}/{total} compressed.')

