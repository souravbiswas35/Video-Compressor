INPUT_SOURCE_PATH = '/content/drive/MyDrive/FYDP Master Folder/FYDP video/SB05 - কাগজ [Kagoz]' # Assumed folder path, as per user

# ── Compression settings ─────────────────────────────────────
CRF        = 28       # Quality: 24 (best) → 32 (smallest). 28 = excellent
CODEC      = 'libx265'  # libx265 = smallest | libx264 = most compatible
PRESET     = 'ultrafast' # ultrafast = 10x faster. Quality still great for short clips
